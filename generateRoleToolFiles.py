#!/usr/bin/python3
"""Generate each Uclusion role's tool file from the MCP server's tool catalog.

Codex and Cursor load every tool definition when a session starts, so their
registrations declare the whole-list description type and the server lists
tool names, input schemas and annotations without any description. Each role
file, and the coordinator SKILL.md, names the tools it uses. This script
renders those tools' full tool and field descriptions into
``skills/uclusion/roles/<role>-tools.md`` and ``roles/coordinator-tools.md``
from ``handlers/mcp_serve.py`` in uclusion_investible_api, run offline the same
way token-manifest tool entries are computed.

Generated files are never edited by hand. ``--check`` writes nothing and exits
1 when any generated file differs from what the backend source produces.

Usage (with a Python that has the investible API's dependencies):
    python3 generateRoleToolFiles.py [--check] \\
        [--api ../uclusion_investible_api] [--common ../uclusion_common]

After regenerating, refresh the installer's WORKFLOW_ASSET_SHA256 pins, count
tokens for the changed files and run ``python3 checkWorkflowAssetPins.py
public/scripts``.
"""

import argparse
import importlib
import os
import re
import sys
import types

ROOT = os.path.dirname(os.path.abspath(__file__))
SKILL_DIR = os.path.join('skills', 'uclusion')
ROLES_DIR = os.path.join(SKILL_DIR, 'roles')
REFERENCE_MARKER = '<!-- uclusion-skill-reference:v1 -->'
REFERENCE_END_MARKER = '<!-- /uclusion-skill-reference:v1 -->'
GENERATED_NOTE = ('<!-- Generated by generateRoleToolFiles.py from the Uclusion MCP tool catalog. '
                  'Do not edit by hand. -->')
TOOLS_LINE = re.compile(r'(?:^|\s)(?:Coordinator tools|Tools): ((?:`[a-z_]+`(?:, |,? and )?)+)', re.MULTILINE)
TOOL_NAME = re.compile(r'`([a-z_]+)`')
GENERATED_SUFFIX = '-tools.md'
# The investible API reads these at import time; none of them is used offline.
OFFLINE_ENVIRONMENT = {
    'logLevel': 'INFO', 'EMAIL_TOPIC_ARN': 'offline', 'VERIFICATION_CODE_SECRET_KEY': 'offline',
    'VERIFICATION_CODE_SIGNING_ALGORITHM': 'HS256', 'marketsServicePrefix': 'offline-',
    'usersServicePrefix': 'offline-', 'asyncServicePrefix': 'offline-', 'AWS_DEFAULT_REGION': 'us-west-2',
    'AWS_ACCESS_KEY_ID': 'offline', 'AWS_SECRET_ACCESS_KEY': 'offline',
    'GLOBAL_CAPABILITY_SECRET_KEY': 'offline', 'CAPABILITY_SIGNING_ALGORITHM': 'HS256',
    'UPLOAD_BUCKET_NAME': 'offline',
}


def load_catalog(api_dir, common_dir):
    """The canonical tool catalog, as an on-demand connection receives it."""
    for key, value in OFFLINE_ENVIRONMENT.items():
        os.environ.setdefault(key, value)
    sys.path[:0] = [os.path.abspath(common_dir), os.path.abspath(api_dir)]
    handler = types.ModuleType('ucommon.handlers.abstract_request_handler')
    handler.handle_request = lambda *args, **kwargs: None
    sys.modules.setdefault('ucommon.handlers.abstract_request_handler', handler)
    mcp_serve = importlib.import_module('handlers.mcp_serve')
    return {tool['name']: tool for tool in mcp_serve.build_tool_catalog()['tools']}


def listed_tools(path):
    """The tool names a role file's single tools line declares, in its order."""
    with open(path, encoding='utf-8') as handle:
        text = handle.read()
    lines = TOOLS_LINE.findall(text)
    if len(lines) > 1:
        raise RuntimeError(f'{path} declares its tools more than once')
    return TOOL_NAME.findall(lines[0]) if lines else []


def role_sources(scripts_dir):
    """(name, source file, generated file) for the coordinator and every role."""
    roles_dir = os.path.join(scripts_dir, ROLES_DIR)
    sources = [('coordinator', os.path.join(scripts_dir, SKILL_DIR, 'SKILL.md'),
                os.path.join(roles_dir, 'coordinator' + GENERATED_SUFFIX))]
    for name in sorted(os.listdir(roles_dir)):
        if name.endswith('.md') and not name.endswith(GENERATED_SUFFIX):
            role = name[:-len('.md')]
            sources.append((role, os.path.join(roles_dir, name),
                            os.path.join(roles_dir, role + GENERATED_SUFFIX)))
    return sources


def field_lines(schema, prefix, lines, seen):
    if not isinstance(schema, dict):
        return
    for name, child in (schema.get('properties') or {}).items():
        path = f'{prefix}.{name}' if prefix else name
        if isinstance(child, dict) and child.get('description') and path not in seen:
            seen.add(path)
            lines.append(f"- `{path}`: {child['description']}")
        field_lines(child, path, lines, seen)
    if isinstance(schema.get('items'), dict):
        field_lines(schema['items'], prefix + '[]', lines, seen)
    for keyword in ('oneOf', 'anyOf', 'allOf'):
        for branch in schema.get(keyword) or []:
            field_lines(branch, prefix, lines, seen)


def render(role, tools, catalog):
    title = 'the coordinator' if role == 'coordinator' else f'the {role} role'
    parts = [REFERENCE_MARKER, GENERATED_NOTE, f'# Tools for {title}', '',
             'The full description of each tool this role uses. A whole-list connection lists these tools '
             'with their fields but without these descriptions.']
    for name in tools:
        if name not in catalog:
            raise RuntimeError(f'{role} lists {name}, which the MCP tool catalog does not define')
        tool = catalog[name]
        parts += ['', f'## `{name}`', '', tool.get('description', '').strip()]
        lines = []
        field_lines(tool.get('inputSchema') or {}, '', lines, set())
        if lines:
            parts += [''] + lines
    parts.append(REFERENCE_END_MARKER)
    return '\n'.join(parts) + '\n'


def generated_files(scripts_dir, catalog):
    files = {}
    for role, source, target in role_sources(scripts_dir):
        tools = listed_tools(source)
        if tools:
            files[target] = render(role, tools, catalog)
    return files


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--scripts', default=os.path.join(ROOT, 'public', 'scripts'))
    parser.add_argument('--api', default=os.path.join(ROOT, '..', 'uclusion_investible_api'))
    parser.add_argument('--common', default=os.path.join(ROOT, '..', 'uclusion_common'))
    parser.add_argument('--check', action='store_true',
                        help='Write nothing; exit 1 when a generated file differs from the backend source.')
    args = parser.parse_args(argv)
    try:
        files = generated_files(args.scripts, load_catalog(args.api, args.common))
    except RuntimeError as error:
        print(f'❌ {error}', file=sys.stderr)
        return 1
    roles_dir = os.path.join(args.scripts, ROLES_DIR)
    stale = sorted(os.path.join(roles_dir, name) for name in os.listdir(roles_dir)
                   if name.endswith(GENERATED_SUFFIX) and os.path.join(roles_dir, name) not in files)
    differing = []
    for path, content in sorted(files.items()):
        current = None
        if os.path.isfile(path):
            with open(path, encoding='utf-8') as handle:
                current = handle.read()
        if current != content:
            differing.append(path)
            if not args.check:
                with open(path, 'w', encoding='utf-8') as handle:
                    handle.write(content)
    if args.check:
        for path in differing:
            print(f'❌ {os.path.relpath(path, args.scripts)} differs from the MCP tool catalog', file=sys.stderr)
        for path in stale:
            print(f'❌ {os.path.relpath(path, args.scripts)} belongs to no role that lists tools', file=sys.stderr)
        if differing or stale:
            print('Run python3 generateRoleToolFiles.py to regenerate them.', file=sys.stderr)
            return 1
        print(f'✅ {len(files)} role tool files match the MCP tool catalog.')
        return 0
    for path in stale:
        os.remove(path)
        print(f'🧹 Removed {os.path.relpath(path, args.scripts)}')
    for path in differing:
        print(f'✍️  Wrote {os.path.relpath(path, args.scripts)}')
    print(f'✅ {len(files)} role tool files match the MCP tool catalog.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
